from sklearn.metrics.pairwise import cosine_similarity

def glove_most_similar(
    word,
    topn=5
):

    if word not in word_to_id:

        print(
            f"'{word}' not found "
            "in GloVe vocabulary"
        )

        return

    word_id = word_to_id[word]

    word_vector = (
        glove_embeddings[word_id]
        .reshape(1, -1)
    )

    similarities = cosine_similarity(
        word_vector,
        glove_embeddings
    )[0]

    similar_ids = (
        similarities
        .argsort()[-topn-1:][::-1]
    )

    results = []

    for idx in similar_ids:

        if idx == word_id:
            continue

        results.append(
            (
                id_to_word[idx],
                similarities[idx]
            )
        )

        if len(results) == topn:
            break

    return results

