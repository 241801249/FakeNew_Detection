class GloVeModel(nn.Module):

    def __init__(
        self,
        vocab_size,
        embedding_dim
    ):

        super().__init__()

        self.word_embeddings = nn.Embedding(
            vocab_size,
            embedding_dim
        )

        self.context_embeddings = nn.Embedding(
            vocab_size,
            embedding_dim
        )

        self.word_bias = nn.Embedding(
            vocab_size,
            1
        )

        self.context_bias = nn.Embedding(
            vocab_size,
            1
        )

    def forward(self, i, j):

        word_vector = (
            self.word_embeddings(i)
        )

        context_vector = (
            self.context_embeddings(j)
        )

        word_bias = (
            self.word_bias(i)
            .squeeze()
        )

        context_bias = (
            self.context_bias(j)
            .squeeze()
        )

        dot_product = (
            word_vector *
            context_vector
        ).sum(dim=1)

        return (
            dot_product
            + word_bias
            + context_bias
        )
