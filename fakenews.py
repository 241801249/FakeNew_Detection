def create_cnn_lstm(embedding_matrix):

    inputs = Input(
        shape=(max_length,)
    )

    embedding = Embedding(
        input_dim=embedding_matrix.shape[0],
        output_dim=embedding_dim,
        weights=[embedding_matrix],
        trainable=True
    )(inputs)

    cnn = Conv1D(
        filters=128,
        kernel_size=3,
        activation="relu"
    )(embedding)

    cnn = GlobalMaxPooling1D()(cnn)

    lstm = LSTM(
        128
    )(embedding)

    combined = Concatenate()([
        cnn,
        lstm
    ])

    x = Dense(
        128,
        activation="relu"
    )(combined)

    x = Dropout(0.5)(x)

    outputs = Dense(
        1,
        activation="sigmoid"
    )(x)

    model = Model(
        inputs,
        outputs
    )

    model.compile(
        optimizer="adam",
        loss="binary_crossentropy",
        metrics=["accuracy"]
    )

    return model

