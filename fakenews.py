class CNN_DistilBERT(nn.Module):

    def __init__(self):
        super().__init__()

        self.distilbert = DistilBertModel.from_pretrained(
            "distilbert-base-uncased"
        )

        self.cnn = nn.Conv1d(
            in_channels=768,
            out_channels=128,
            kernel_size=3
        )

        self.pool = nn.AdaptiveMaxPool1d(1)

        self.fc1 = nn.Linear(
            128,
            128
        )

        self.dropout = nn.Dropout(0.5)

        self.fc2 = nn.Linear(
            128,
            1
        )

    def forward(
        self,
        input_ids,
        attention_mask
    ):

        outputs = self.distilbert(
            input_ids=input_ids,
            attention_mask=attention_mask
        )

        x = outputs.last_hidden_state

        x = x.permute(
            0,
            2,
            1
        )

        x = self.cnn(x)

        x = torch.relu(x)

        x = self.pool(x)

        x = x.squeeze(2)

        x = self.fc1(x)

        x = torch.relu(x)

        x = self.dropout(x)

        x = self.fc2(x)

        return x

