def glove_loss(
    prediction,
    target
):

    x_max = 100

    alpha = 0.75

    weight = torch.where(
        target < x_max,
        (target / x_max) ** alpha,
        torch.ones_like(target)
    )

    loss = weight * (
        prediction -
        torch.log(target)
    ) ** 2

    return loss.mean()
